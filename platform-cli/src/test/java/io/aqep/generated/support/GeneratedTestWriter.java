package io.aqep.generated.support;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import io.aqep.shared.Action;
import io.aqep.shared.Assertion;
import io.aqep.shared.ExecutableScenario;
import io.aqep.shared.StepTrace;
import java.io.IOException;
import java.net.URI;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Turns AI-generated scenarios into permanent Page Object Model tests (pages / steps / tests) per site.
 * Scenarios accumulate in a registry (scenarios.json): new ones are added, existing ones are never deleted,
 * and the Java sources are rebuilt from the whole registry, so every earlier test keeps existing.
 */
public final class GeneratedTestWriter {
    private static final String ROOT_PACKAGE = "io.aqep.generated";
    private static final String HEADER = "// GENERATED by AQEP from AI scenarios. Source of truth: "
            + "src/test/resources/generated/%s/scenarios.json - regenerated on every full run.\n";
    private final ObjectMapper mapper = new ObjectMapper().enable(SerializationFeature.INDENT_OUTPUT);

    public record AssertionSpec(String type, String locator, String value) { }

    /** One user action (CLICK or SEARCH) on pageUrl, the page it led to and how that is verified (nullable). */
    public record StepSpec(String type, String pageUrl, String locator, String term, String resultUrl,
                           String expectUrl, String expectTitle) {
        StepSpec(String type, String pageUrl, String locator, String term) {
            this(type, pageUrl, locator, term, null, null, null);
        }
    }

    public record ScenarioSpec(String name, String category, String description, String startUrl,
                               String clickLocator, String searchLocator, String searchTerm,
                               List<AssertionSpec> assertions, List<StepSpec> steps, String endUrl) {
        /** Registry entries written before multi-step support only carry the single click/search fields. */
        List<StepSpec> effectiveSteps() {
            if (steps != null) return steps;
            List<StepSpec> legacy = new ArrayList<>();
            if (clickLocator != null) legacy.add(new StepSpec("CLICK", startUrl, clickLocator, null));
            if (searchLocator != null) legacy.add(new StepSpec("SEARCH", startUrl, searchLocator, searchTerm));
            return legacy;
        }

        String finalUrl() {
            return endUrl == null || endUrl.isBlank() ? startUrl : endUrl;
        }

        String key() {
            return startUrl + "|" + effectiveSteps() + "|" + assertions;
        }
    }

    public record Result(String site, int added, int total, Path suiteFile, Path allSuiteFile, Path packageDirectory) { }

    public Optional<Result> write(List<ExecutableScenario> scenarios, Path sourceRoot, Path resourceRoot)
            throws IOException {
        List<ScenarioSpec> incoming = scenarios.stream().map(this::toSpec).flatMap(Optional::stream).toList();
        if (incoming.isEmpty() || !Files.isDirectory(sourceRoot)) return Optional.empty();
        String slug = siteSlug(incoming.get(0).startUrl());
        Path registry = resourceRoot.resolve("generated").resolve(slug).resolve("scenarios.json");
        List<ScenarioSpec> all = new ArrayList<>();
        if (Files.isRegularFile(registry)) {
            all.addAll(List.of(mapper.readValue(registry.toFile(), ScenarioSpec[].class)));
        }
        int added = 0;
        for (ScenarioSpec spec : incoming) {
            if (all.stream().anyMatch(existing -> existing.key().equals(spec.key()))) continue;
            String name = spec.name();
            for (int copy = 2; hasName(all, name); copy++) name = spec.name() + " " + copy;
            all.add(new ScenarioSpec(name, spec.category(), spec.description(), spec.startUrl(), spec.clickLocator(),
                    spec.searchLocator(), spec.searchTerm(), spec.assertions(), spec.steps(), spec.endUrl()));
            added++;
        }
        Files.createDirectories(registry.getParent());
        mapper.writeValue(registry.toFile(), all);
        Path packageDirectory = generateSources(slug, all, sourceRoot);
        Path suites = resourceRoot.resolve("suites").resolve("generated");
        Files.createDirectories(suites);
        Path suiteFile = suites.resolve("testng-generated-" + slug + ".xml");
        Files.writeString(suiteFile, suiteXml(slug, all));
        Path allSuite = suites.resolve("testng-generated-all.xml");
        Files.writeString(allSuite, allSuiteXml(sourceRoot));
        return Optional.of(new Result(slug, added, all.size(), suiteFile, allSuite, packageDirectory));
    }

    private boolean hasName(List<ScenarioSpec> specs, String name) {
        return specs.stream().anyMatch(spec -> spec.name().equals(name));
    }

    private Optional<ScenarioSpec> toSpec(ExecutableScenario scenario) {
        List<StepSpec> steps = new ArrayList<>();
        for (int i = 0; i < scenario.actions().size(); i++) {
            StepTrace trace = i < scenario.trace().size() ? scenario.trace().get(i)
                    : new StepTrace(scenario.targetPage(), null, null, null);
            Action action = scenario.actions().get(i);
            if (action instanceof Action.ClickAction c) {
                steps.add(new StepSpec("CLICK", trace.pageUrl(), c.locator(), null, trace.resultUrl(),
                        trace.expectUrlPart(), trace.expectTitlePart()));
            }
            if (action instanceof Action.SearchAction s) {
                steps.add(new StepSpec("SEARCH", trace.pageUrl(), s.searchInputLocator(), s.searchTerm(),
                        trace.resultUrl(), trace.expectUrlPart(), trace.expectTitlePart()));
            }
        }
        String endUrl = scenario.trace().isEmpty() ? scenario.targetPage()
                : scenario.trace().get(scenario.trace().size() - 1).resultUrl();
        List<AssertionSpec> assertions = new ArrayList<>();
        for (Assertion assertion : scenario.assertions()) {
            if (assertion instanceof Assertion.UrlContainsAssertion a) {
                assertions.add(new AssertionSpec("URL_CONTAINS", null, a.expectedUrlPart()));
            } else if (assertion instanceof Assertion.PageTitleAssertion a) {
                assertions.add(new AssertionSpec("TITLE_CONTAINS", null, a.expectedTitle()));
            } else if (assertion instanceof Assertion.ElementVisibleAssertion a) {
                assertions.add(new AssertionSpec("ELEMENT_VISIBLE", a.locator(), null));
            }
        }
        if (assertions.isEmpty() || scenario.targetPage() == null || scenario.targetPage().isBlank()) {
            return Optional.empty();
        }
        String description = scenario.description().orElse("");
        int colon = description.indexOf(':');
        String category = colon > 0 ? description.substring(0, colon).strip() : "General";
        String rationale = colon > 0 ? description.substring(colon + 1).strip() : description;
        return Optional.of(new ScenarioSpec(scenario.name(), category, rationale, scenario.targetPage(),
                null, null, null, assertions, steps, endUrl));
    }

    // ---------------------------------------------------------------- source generation

    private Path generateSources(String slug, List<ScenarioSpec> specs, Path sourceRoot) throws IOException {
        String basePackage = ROOT_PACKAGE + "." + slug;
        Path baseDirectory = sourceRoot.resolve(basePackage.replace('.', '/'));
        Files.createDirectories(baseDirectory.resolve("pages"));
        Files.createDirectories(baseDirectory.resolve("steps"));
        Files.createDirectories(baseDirectory.resolve("tests"));
        String header = HEADER.formatted(slug);

        Map<String, PageModel> pages = new LinkedHashMap<>();
        Map<ScenarioSpec, String> methodNames = new LinkedHashMap<>();
        StringBuilder stepMethods = new StringBuilder();
        for (ScenarioSpec spec : specs) {
            String method = uniqueMethodName(spec.name(), methodNames.values());
            methodNames.put(spec, method);
            stepMethods.append(stepMethod(spec, method, pages));
        }
        for (PageModel page : pages.values()) {
            Files.writeString(baseDirectory.resolve("pages").resolve(page.className + ".java"),
                    pageSource(basePackage, header, page));
        }
        String stepsClass = camel(slug) + "Steps";
        Files.writeString(baseDirectory.resolve("steps").resolve(stepsClass + ".java"), """
                %spackage %s.steps;

                import io.aqep.core.execution.ActionContext;
                import io.qameta.allure.Step;
                %s
                /** Business-level steps for %s; each step composes page objects. */
                public class %s {
                    private final ActionContext ctx;

                    public %s(ActionContext ctx) {
                        this.ctx = ctx;
                    }
                %s}
                """.formatted(header, basePackage, pageImports(basePackage, pages), slug, stepsClass, stepsClass,
                stepMethods));

        // One test class per scenario; stale classes from earlier layouts are removed first.
        Path testsDirectory = baseDirectory.resolve("tests");
        try (Stream<Path> old = Files.list(testsDirectory)) {
            for (Path file : old.filter(path -> path.toString().endsWith("Test.java")).toList()) Files.delete(file);
        }
        for (ScenarioSpec spec : specs) {
            String testClass = testClassName(slug, methodNames.get(spec));
            Files.writeString(testsDirectory.resolve(testClass + ".java"),
                    testSource(basePackage, header, slug, stepsClass, testClass, List.of(spec), methodNames));
        }
        return baseDirectory;
    }

    private String pageImports(String basePackage, Map<String, PageModel> pages) {
        StringBuilder imports = new StringBuilder();
        for (String name : pages.keySet()) imports.append("import ").append(basePackage).append(".pages.")
                .append(name).append(";\n");
        return imports.toString();
    }

    private static PageModel pageFor(Map<String, PageModel> pages, String url) {
        return pages.computeIfAbsent(pageClassName(url), name -> new PageModel(name, normalizeUrl(url)));
    }

    private String stepMethod(ScenarioSpec spec, String method, Map<String, PageModel> pages) {
        StringBuilder body = new StringBuilder();
        Map<String, String> variables = new LinkedHashMap<>();
        PageModel start = pageFor(pages, spec.startUrl());
        PageModel current = start;
        String variable = variableFor(variables, start);
        body.append("        ").append(start.className).append(' ').append(variable)
                .append(" = new ").append(start.className).append("(ctx).open();\n");
        for (StepSpec step : spec.effectiveSteps()) {
            PageModel page = pageFor(pages, step.pageUrl());
            if (page != current) {
                current = page;
                variable = switchTo(body, variables, page);
            }
            if (step.type().equals("CLICK")) {
                body.append("        ").append(variable).append('.').append(page.clickMethod(step.locator()))
                        .append("();\n");
            } else {
                body.append("        ").append(variable).append(".searchFor(\"").append(java(step.term()))
                        .append("\");\n");
                page.usesSearch(step.locator());
            }
            String resultUrl = step.resultUrl() == null ? step.pageUrl() : step.resultUrl();
            PageModel reached = pageFor(pages, resultUrl);
            if (reached != current) {
                current = reached;
                variable = switchTo(body, variables, reached);
            }
            if (step.expectUrl() != null) {
                body.append("        ").append(variable).append(".assertUrlContains(\"")
                        .append(java(step.expectUrl())).append("\");\n");
            }
            if (step.expectTitle() != null) {
                body.append("        ").append(variable).append(".assertTitleContains(\"")
                        .append(java(step.expectTitle())).append("\");\n");
            }
        }
        PageModel last = pageFor(pages, spec.finalUrl());
        if (last != current) {
            current = last;
            variable = switchTo(body, variables, last);
        }
        PageModel page = current;
        for (AssertionSpec assertion : spec.assertions()) {
            switch (assertion.type()) {
                case "URL_CONTAINS" -> body.append("        ").append(variable).append(".assertUrlContains(\"")
                        .append(java(assertion.value())).append("\");\n");
                case "TITLE_CONTAINS" -> body.append("        ").append(variable).append(".assertTitleContains(\"")
                        .append(java(assertion.value())).append("\");\n");
                default -> body.append("        ").append(variable).append('.')
                        .append(page.visibleMethod(assertion.locator())).append("();\n");
            }
        }
        return "\n    @Step(\"" + java(spec.name()) + "\")\n    public void " + method + "() {\n" + body + "    }\n";
    }

    /** Wraps the page the browser has navigated to in its page object (declaring the variable on first use). */
    private static String switchTo(StringBuilder body, Map<String, String> variables, PageModel page) {
        boolean known = variables.containsKey(page.className);
        String variable = variableFor(variables, page);
        body.append("        ").append(known ? "" : page.className + " ").append(variable).append(" = new ")
                .append(page.className).append("(ctx);\n");
        return variable;
    }

    private static String variableFor(Map<String, String> variables, PageModel page) {
        return variables.computeIfAbsent(page.className,
                name -> Character.toLowerCase(name.charAt(0)) + name.substring(1));
    }

    private String pageSource(String basePackage, String header, PageModel page) {
        StringBuilder constants = new StringBuilder();
        StringBuilder methods = new StringBuilder();
        for (var element : page.elements.values()) {
            constants.append("    private static final String ").append(element.constant).append(" = \"")
                    .append(java(element.locator)).append("\";\n");
            methods.append("\n    @Step(\"").append(java(element.step)).append("\")\n    public ").append(page.className)
                    .append(' ').append(element.method).append(element.kind.equals("search") ? "(String term)" : "()")
                    .append(" {\n        ").append(switch (element.kind) {
                        case "click" -> "click(" + element.constant + ")";
                        case "search" -> "search(" + element.constant + ", term)";
                        default -> "assertVisible(" + element.constant + ")";
                    }).append(";\n        return this;\n    }\n");
        }
        return """
                %spackage %s.pages;

                import io.aqep.core.execution.ActionContext;
                import io.aqep.generated.support.BasePage;
                import io.qameta.allure.Step;

                /** Page object for %s. */
                public class %s extends BasePage {
                    public static final String URL = "%s";
                %s
                    public %s(ActionContext ctx) {
                        super(ctx);
                    }

                    @Step("Open %s")
                    public %s open() {
                        open(URL);
                        return this;
                    }
                %s}
                """.formatted(header, basePackage, java(page.url), page.className, java(page.url), constants,
                page.className, java(page.url), page.className, methods);
    }

    private String testSource(String basePackage, String header, String slug, String stepsClass, String testClass,
                              List<ScenarioSpec> specs, Map<ScenarioSpec, String> methodNames) {
        String category = specs.get(0).category();
        String categoryTag = category.toLowerCase().replaceAll("[^a-z0-9]+", "-");
        String severity = switch (category.toUpperCase()) {
            case "NAVIGATION", "SEARCH", "FORMS", "FORM", "FUNCTIONAL", "CRITICAL" -> "CRITICAL";
            case "VISUAL" -> "MINOR";
            default -> "NORMAL";
        };
        StringBuilder tests = new StringBuilder();
        int priority = 1;
        for (ScenarioSpec spec : specs) {
            String method = methodNames.get(spec);
            tests.append("""

                        @Test(description = "%s", groups = {"generated", "regression", "%s", "%s", "ui"}, priority = %d,
                                retryAnalyzer = RetryOnce.class)
                        @Story("%s")
                        @Severity(SeverityLevel.%s)
                        @Description("%s")
                        public void %s() {
                            steps().%s();
                        }
                    """.formatted(java(spec.name()), slug, categoryTag, priority++, java(spec.name()), severity,
                    java(spec.description()), method, method));
        }
        return """
                %spackage %s.tests;

                import io.aqep.generated.support.GeneratedTestBase;
                import io.aqep.generated.support.RetryOnce;
                import %s.steps.%s;
                import io.qameta.allure.Description;
                import io.qameta.allure.Epic;
                import io.qameta.allure.Feature;
                import io.qameta.allure.Severity;
                import io.qameta.allure.SeverityLevel;
                import io.qameta.allure.Story;
                import org.testng.annotations.Test;

                @Epic("%s")
                @Feature("%s")
                public class %s extends GeneratedTestBase {
                    private %s steps() {
                        return new %s(ctx);
                    }
                %s}
                """.formatted(header, basePackage, basePackage, stepsClass, java(slug), java(category), testClass,
                stepsClass, stepsClass, tests);
    }

    // ---------------------------------------------------------------- suites

    private String suiteXml(String slug, List<ScenarioSpec> specs) {
        StringBuilder tests = new StringBuilder();
        List<String> methods = new ArrayList<>();
        for (ScenarioSpec spec : specs) {
            String method = uniqueMethodName(spec.name(), methods);
            methods.add(method);
            String testClass = testClassName(slug, method);
            tests.append("    <test name=\"").append(testClass).append("\">\n        <classes>\n"
                    + "            <class name=\"" + ROOT_PACKAGE + "." + slug + ".tests." + testClass + "\"/>\n"
                    + "        </classes>\n    </test>\n");
        }
        return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE suite SYSTEM \"https://testng.org/testng-1.0.dtd\">\n"
                + "<!-- Generated. Run one test alone from the IDE gutter, or this suite for " + slug + ". -->\n"
                + "<suite name=\"Generated-" + slug + "\" verbose=\"2\">\n"
                + "    <parameter name=\"headless\" value=\"true\"/>\n" + tests + "</suite>\n";
    }

    private String allSuiteXml(Path sourceRoot) throws IOException {
        StringBuilder tests = new StringBuilder();
        Path generated = sourceRoot.resolve(ROOT_PACKAGE.replace('.', '/'));
        try (Stream<Path> files = Files.walk(generated)) {
            files.filter(path -> path.getParent() != null && path.getParent().getFileName().toString().equals("tests")
                            && path.toString().endsWith("Test.java")).sorted().forEach(path -> {
                String site = path.getParent().getParent().getFileName().toString();
                String cls = path.getFileName().toString().replace(".java", "");
                tests.append("    <test name=\"").append(site).append(" - ").append(cls).append("\">\n        <classes>\n"
                        + "            <class name=\"" + ROOT_PACKAGE + "." + site + ".tests." + cls + "\"/>\n"
                        + "        </classes>\n    </test>\n");
            });
        }
        return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE suite SYSTEM \"https://testng.org/testng-1.0.dtd\">\n"
                + "<!-- Generated. Runs every generated site test. -->\n"
                + "<suite name=\"Generated-all-sites\" verbose=\"2\">\n    <parameter name=\"headless\" value=\"true\"/>\n"
                + tests + "</suite>\n";
    }

    // ---------------------------------------------------------------- naming helpers

    private static final class PageModel {
        final String className;
        final String url;
        final Map<String, Element> elements = new LinkedHashMap<>();

        PageModel(String className, String url) {
            this.className = className;
            this.url = url;
        }

        String clickMethod(String locator) {
            return element("click", locator, "click" + camel(label(locator)) + suffix(locator), "Click ").method;
        }

        String visibleMethod(String locator) {
            return element("visible", locator, "assert" + camel(label(locator)) + "Visible", "Verify visible: ").method;
        }

        void usesSearch(String locator) {
            element("search", locator, "searchFor", "Search for a term");
        }

        private Element element(String kind, String locator, String method, String stepPrefix) {
            return elements.computeIfAbsent(kind + "|" + locator, key -> {
                String unique = method;
                for (int i = 2; hasMethod(unique); i++) unique = method + i;
                return new Element(kind, locator, unique, upperSnake(unique),
                        stepPrefix + (kind.equals("search") ? "" : "'" + label(locator) + "'"));
            });
        }

        private boolean hasMethod(String method) {
            return method.equals("open") || elements.values().stream().anyMatch(e -> e.method.equals(method));
        }
    }

    private record Element(String kind, String locator, String method, String constant, String step) { }

    private static String suffix(String locator) {
        return locator.startsWith("role=link") ? "Link" : locator.startsWith("role=button") ? "Button" : "";
    }

    private static String label(String locator) {
        Matcher name = Pattern.compile("name=\"([^\"]*)\"").matcher(locator);
        if (name.find()) return name.group(1);
        Matcher id = Pattern.compile("#([A-Za-z0-9_-]+)").matcher(locator);
        if (id.find()) return id.group(1);
        return locator.replaceFirst("^[a-z-]+=", "").replaceAll(" >> nth=\\d+$", "");
    }

    private static String pageClassName(String url) {
        String path = path(url);
        String name = camel(path.replaceAll("/+", " "));
        return (name.isEmpty() || name.equals("Page") ? "Home" : name) + "Page";
    }

    private static String normalizeUrl(String url) {
        return url.replaceAll("[?#].*$", "");
    }

    private static String path(String url) {
        try {
            String path = URI.create(url).getPath();
            return path == null ? "" : path;
        } catch (IllegalArgumentException exception) {
            return "";
        }
    }

    private static String siteSlug(String url) {
        String host = "site";
        try {
            host = URI.create(url).getHost() == null ? host : URI.create(url).getHost();
        } catch (IllegalArgumentException ignored) {
            // keeps the default slug
        }
        List<String> labels = new ArrayList<>(List.of(host.replaceFirst("^www\\.", "").split("\\.")));
        if (labels.size() > 1) labels.remove(labels.size() - 1);
        // amazon.co.uk -> drop the "co" second-level suffix too; docs.python.org -> python
        if (labels.size() > 1 && List.of("co", "com", "org", "net", "gov", "edu", "ac").contains(
                labels.get(labels.size() - 1))) labels.remove(labels.size() - 1);
        String slug = labels.get(labels.size() - 1).toLowerCase().replaceAll("[^a-z0-9]", "");
        if (slug.isEmpty()) slug = "site";
        return Character.isDigit(slug.charAt(0)) ? "site" + slug : slug;
    }

    private static String uniqueMethodName(String scenarioName, Iterable<String> used) {
        String base = lowerCamel(scenarioName);
        if (base.isEmpty()) base = "scenario";
        String name = base;
        for (int i = 2; contains(used, name); i++) name = base + i;
        return name;
    }

    private static boolean contains(Iterable<String> values, String value) {
        for (String candidate : values) if (candidate.equals(value)) return true;
        return false;
    }

    static String camel(String text) {
        StringBuilder result = new StringBuilder();
        for (String part : text.split("[^A-Za-z0-9]+")) {
            if (part.isEmpty()) continue;
            if (part.length() > 1 && part.equals(part.toUpperCase()) && !part.matches("\\d+")) part = part.toLowerCase();
            result.append(Character.toUpperCase(part.charAt(0))).append(part.substring(1));
        }
        if (!result.isEmpty() && Character.isDigit(result.charAt(0))) result.insert(0, 'N');
        return result.toString();
    }

    private static String testClassName(String slug, String method) {
        return camel(slug) + Character.toUpperCase(method.charAt(0)) + method.substring(1) + "Test";
    }

    private static String lowerCamel(String text) {
        String camel = camel(text);
        return camel.isEmpty() ? camel : Character.toLowerCase(camel.charAt(0)) + camel.substring(1);
    }

    private static String upperSnake(String methodName) {
        return methodName.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toUpperCase();
    }

    private static String java(String value) {
        return value == null ? "" : value.replace("\\", "\\\\").replace("\"", "\\\"")
                .replace("\r", " ").replace("\n", " ");
    }
}
